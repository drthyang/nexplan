/**
 * SHA-256 of a text's UTF-8 bytes, as lowercase hex, for the provenance record.
 * Browsers expose crypto.subtle only on secure origins (HTTPS or localhost), so
 * a page opened over plain HTTP, e.g. a laptop's preview from a phone on the
 * same network or an intranet server, falls back to the FIPS 180-4 algorithm
 * below. Both give the same digest; sha256.test.ts checks it against node:crypto.
 */

